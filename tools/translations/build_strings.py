"""Builds app/src/main/res/values-XX/strings.xml from a simple translation file.

Each line of tools/translations/<lang>.txt is `key|text`:
  - plain strings:   name|Text
  - plurals:         name#one|Text   name#other|Text
  - string arrays:   name[0]|Text   (the text may itself contain "|")
Write apostrophes and quotes plainly; they are escaped here. Keep %1$s style placeholders.
Strings missing from a translation fall back to English at runtime.

Usage: python tools/translations/build_strings.py es values-es
"""
import re
import sys
from collections import OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def escape(text: str) -> str:
    text = text.replace('&amp;', '&').replace('&', '&amp;')
    text = text.replace('<', '&lt;').replace('>', '&gt;')
    text = re.sub(r"(?<!\\)'", r"\\'", text)
    text = re.sub(r'(?<!\\)"', r'\\"', text)
    if text.startswith('@') or text.startswith('?'):
        text = '\\' + text
    return text


def build(lang: str, folder: str) -> Path:
    strings: "OrderedDict[str, str]" = OrderedDict()
    plurals: "OrderedDict[str, OrderedDict[str, str]]" = OrderedDict()
    arrays: "OrderedDict[str, dict[int, str]]" = OrderedDict()
    for raw in (ROOT / 'tools' / 'translations' / f'{lang}.txt').read_text(encoding='utf-8').splitlines():
        if not raw.strip() or raw.startswith('//'):
            continue
        key, _, text = raw.partition('|')
        key = key.strip()
        if m := re.fullmatch(r'(\w+)#(zero|one|two|few|many|other)', key):
            plurals.setdefault(m.group(1), OrderedDict())[m.group(2)] = text
        elif m := re.fullmatch(r'(\w+)\[(\d+)\]', key):
            arrays.setdefault(m.group(1), {})[int(m.group(2))] = text
        else:
            strings[key] = text
    out = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Generated by tools/translations/build_strings.py. Edit tools/translations/'
           f'{lang}.txt instead. -->', '<resources>']
    for name, text in strings.items():
        out.append(f'    <string name="{name}">{escape(text)}</string>')
    for name, items in plurals.items():
        out.append(f'    <plurals name="{name}">')
        for quantity, text in items.items():
            out.append(f'        <item quantity="{quantity}">{escape(text)}</item>')
        out.append('    </plurals>')
    for name, items in arrays.items():
        out.append(f'    <string-array name="{name}">')
        for index in sorted(items):
            out.append(f'        <item>{escape(items[index])}</item>')
        out.append('    </string-array>')
    out.append('</resources>')
    target = ROOT / 'app' / 'src' / 'main' / 'res' / folder / 'strings.xml'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('\n'.join(out) + '\n', encoding='utf-8')
    return target


if __name__ == '__main__':
    print(build(sys.argv[1], sys.argv[2]))
